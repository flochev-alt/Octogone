// --- Conversion d'unités ---
export function formatHeight(cm, lang) {
  if (cm == null) return null;
  if (lang !== "en") return `${cm} cm`;
  const totalInches = cm / 2.54;
  const feet = Math.floor(totalInches / 12);
  const inches = Math.round(totalInches % 12);
  return `${feet}'${inches}"`;
}

